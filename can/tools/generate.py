#!/usr/bin/env python3
"""Generate C code from the DBC files into can/gen.

  python can/tools/generate.py           write the files
  python can/tools/generate.py --check   fail if can/gen is not exactly what would be generated

Outputs (all deterministic, no timestamps):
  can/gen/*.c, *.h                 pack/unpack code (cantools) and per-message supervision tables
  docs/generated/can_messages.md   message list for the ESF / TVSD and for the team handbooks
DBC files without messages (placeholders) produce no code files.
"""
from __future__ import annotations

import argparse
import re
import sys

import dbc_util as u
from cantools.database.can import c_source

HEADER = "/* GENERATED by can/tools/generate.py from can/dbc/{dbc}. DO NOT EDIT. */\n"

CFG_H = """\
/* GENERATED by can/tools/generate.py. DO NOT EDIT. */
#ifndef CAN_MSG_CFG_H
#define CAN_MSG_CFG_H

#include <stdbool.h>
#include <stdint.h>

/* Per-message supervision data taken from the DBC attributes. */
typedef struct {
    uint32_t    frame_id;
    uint8_t     dlc;
    uint16_t    period_ms;       /* GenMsgCycleTime */
    uint16_t    rx_timeout_ms;   /* RxTimeoutMs; 0 = the VCU does not receive this message */
    char        safety_class;    /* 'A', 'B' or 'C' (SafetyClass) */
    uint8_t     data_id;         /* DataId; 0 = no E2E header */
    bool        vcu_tx;          /* true if the VCU is the sender */
    const char *name;
} can_msg_cfg_t;

#endif /* CAN_MSG_CFG_H */
"""

TS_RE = re.compile(
    r"(generated by cantools version \S+) [A-Z][a-z]{2} [A-Z][a-z]{2} +\d+ \d\d:\d\d:\d\d \d{4}\.")


def normalise(text: str) -> str:
    text = TS_RE.sub(r"\1.", text)
    text = "\n".join(line.rstrip() for line in text.splitlines())
    return text + "\n"


def supervision_header(name: str, db) -> str:
    up = name.upper()
    rows = []
    for m in sorted(db.messages, key=lambda x: x.frame_id):
        rows.append(
            "    {{ 0x{fid:03X}u, {dlc}u, {cyc}u, {rxt}u, '{cls}', 0x{did:02X}u, {tx}, \"{nm}\" }},".format(
                fid=m.frame_id, dlc=m.length, cyc=u.cycle_ms(m), rxt=u.rx_timeout_ms(m),
                cls=u.safety_class(m), did=u.data_id(m),
                tx="true" if u.vcu_is_sender(m) else "false", nm=m.name))
    return (
        f"/* GENERATED by can/tools/generate.py from can/dbc/{name}.dbc. DO NOT EDIT. */\n"
        f"#ifndef {up}_SUPERVISION_H\n#define {up}_SUPERVISION_H\n\n"
        '#include "can_msg_cfg.h"\n\n'
        f"#define {up}_MSG_COUNT {len(db.messages)}u\n\n"
        f"static const can_msg_cfg_t {name}_msg_cfg[{up}_MSG_COUNT] = {{\n"
        + "\n".join(rows)
        + f"\n}};\n\n#endif /* {up}_SUPERVISION_H */\n"
    )


BUS_TITLE = {"veh": "VEH-CAN", "svc": "SVC-CAN", "pt_dti_r4": "PT-CAN"}


def messages_markdown(dbs: dict) -> str:
    lines = [
        "<!-- GENERATED by can/tools/generate.py from can/dbc/*.dbc. DO NOT EDIT. -->",
        "# CAN message list (generated)",
        "",
        "Source of truth: the DBC files in `can/dbc`. Periods, timeouts, safety classes and DataIds are DBC attributes.",
        "",
    ]
    for name, db in dbs.items():
        title = BUS_TITLE.get(name, name)
        rate = u.BUS_BITRATE[name]
        lines += [f"## {title} (`{name}.dbc`, {rate // 1000} kbit/s)", ""]
        if not db.messages:
            lines += ["_No messages defined yet (placeholder)._", ""]
            continue
        lines += ["| ID | Name | Sender | DLC | Period ms | Class | Rx timeout ms | DataId | Signals |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for m in sorted(db.messages, key=lambda x: x.frame_id):
            width = 8 if m.is_extended_frame else 3
            did = u.data_id(m)
            lines.append("| `0x{:0{w}X}` | {} | {} | {} | {} | {} | {} | {} | {} |".format(
                m.frame_id, m.name, ", ".join(m.senders), m.length, u.cycle_ms(m), u.safety_class(m),
                u.rx_timeout_ms(m) or "-", f"0x{did:02X}" if did else "-",
                ", ".join(sg.name for sg in m.signals), w=width))
        lines.append("")
    return "\n".join(lines) + "\n"


def generate() -> dict[str, str]:
    out: dict[str, str] = {}
    any_msgs = False
    dbs: dict = {}
    for path in u.dbc_files():
        name = path.stem
        db = u.load(path)
        dbs[name] = db
        if not db.messages:
            continue
        any_msgs = True
        h, s, _fuzz, _mk = c_source.generate(
            db, name, f"{name}.h", f"{name}.c", f"{name}_fuzzer.c", use_float=True, use_round=True)
        out[f"can/gen/{name}.h"] = normalise(h)
        out[f"can/gen/{name}.c"] = normalise(s)
        out[f"can/gen/{name}_supervision.h"] = supervision_header(name, db)
    if any_msgs:
        out["can/gen/can_msg_cfg.h"] = CFG_H
    out["docs/generated/can_messages.md"] = messages_markdown(dbs)
    return out


GENERATED_DIRS = ("can/gen", "docs/generated")
KEEP = {"README.md"}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    files = generate()

    if args.check:
        problems = []
        for rel, text in files.items():
            p = u.ROOT / rel
            if not p.exists():
                problems.append(f"missing: {rel}")
            elif p.read_text(encoding="utf-8") != text:
                problems.append(f"stale:   {rel}")
        for d in GENERATED_DIRS:
            folder = u.ROOT / d
            if folder.exists():
                for p in sorted(folder.iterdir()):
                    rel = f"{d}/{p.name}"
                    if rel not in files and p.name not in KEEP:
                        problems.append(f"extra:   {rel}")
        if problems:
            print("Generated files are not up to date. Run: python can/tools/generate.py")
            for line in problems:
                print("  -", line)
            return 1
        print(f"generated files are up to date ({len(files)} files)")
        return 0

    for d in GENERATED_DIRS:
        folder = u.ROOT / d
        folder.mkdir(parents=True, exist_ok=True)
        for p in folder.iterdir():
            if p.is_file() and p.name not in KEEP:
                p.unlink()
    for rel, text in files.items():
        (u.ROOT / rel).write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
